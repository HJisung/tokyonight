const panes = (page: Page) => page.locator('.pane:visible')
const treeFile = (page: Page, name: string) => page.locator('.tree-item').filter({ hasText: name })
async function end(page: Page, content: Locator) {
  await content.focus()
  const mac = await page.evaluate(() => navigator.platform.includes('Mac'))
  await page.keyboard.press(mac ? 'Meta+ArrowDown' : 'Control+End')
}
async function typeEnd(page: Page, content: Locator, text: string) {
  await end(page, content)
  await page.keyboard.insertText(text)
}
async function openGuide(page: Page) {
  await page.goto('/')
  await treeFile(page, '시작하기.md').click()
  await expect(page.locator('.cm-content')).toContainText('나만의 작업실')
  await end(page, page.locator('.cm-content'))
}
async function source(page: Page, pane = panes(page).first()) {
  if (await pane.locator('.cm-tn-source').isVisible()) return
  await pane.locator('.pane-tools').getByRole('button', { name: '원문', exact: true }).click()
  await expect(pane.locator('.cm-tn-source')).toBeVisible()
}
async function prompt(page: Page, value: string) {
  await page.getByRole('dialog').getByRole('textbox').fill(value)
  await page.getByRole('dialog').getByRole('button', { name: '확인', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
}
async function menu(page: Page, filename: string, item: string) {
  await treeFile(page, filename).click({ button: 'right' })
  await page.getByRole('menuitem', { name: item, exact: true }).click()
}

