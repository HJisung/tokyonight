test('표 밖 원문과 BOM·CRLF·마지막 줄바꿈을 보존한다', async ({ page, backend }) => {
  backend.app.last = ROOT
  const prefix = '\ufeff앞 문단 Ω\r\n\r\n'
  const suffix = '뒤 문단 Z'
  backend.put(GUIDE, prefix + MARKDOWN.replace(/\n/g, '\r\n') + suffix)
  await openGuide(page)
  await page.locator('.cm-tn-table').getByRole('cell', { name: '디자인', exact: true }).fill('표 안만 변경')
  await expect.poll(() => backend.text(GUIDE)).toContain('표 안만 변경')
  const raw = backend.text(GUIDE)
  expect(raw.startsWith(prefix)).toBe(true)
  expect(raw.endsWith(suffix)).toBe(true)
  expect(raw.match(/(?<!\r)\n/)).toBeNull()
  expect(raw.charCodeAt(0)).toBe(0xfeff)
  // 다른 형식의 디스크 내용을 받아들인 뒤에도 끝 줄을 임의로 붙이거나 빼지 않는다.
  backend.put(GUIDE, '# 끝줄 확인\n\n끝\n')
  await emit(page, 'fs-changed', [GUIDE])
  await expect(page.locator('.cm-content')).toContainText('끝줄 확인')
  await source(page)
  await page.locator('.cm-content').focus()
  const mac = await page.evaluate(() => navigator.platform.includes('Mac'))
  await page.keyboard.press(mac ? 'Meta+ArrowUp' : 'Control+Home')
  await page.keyboard.insertText('추가 ')
  await expect.poll(() => backend.text(GUIDE)).toBe('추가 # 끝줄 확인\n\n끝\n')
})
